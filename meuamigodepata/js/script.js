  dropdown.classList.toggle('aberto');

  // Altera a seta
  const seta = botao.querySelector('.seta');

  if (dropdown.classList.contains('aberto')) {
    seta.textContent = '▲';
  } else {
    seta.textContent = '▼';
  }
