    /* =========================================
       APLICAR TODOS OS FILTROS
    ========================================= */

    function aplicarFiltros() {

      const cards =
        document.querySelectorAll(".card");
        
    


      /* =========================
         ESTADO
      ========================= */

      const estadoSelecionado =
        document.querySelector(
          'input[name="uf"]:checked'
        )?.value || "";


      /* =========================
         CIDADE
      ========================= */

      const cidadeSelecionada =
        document.querySelector(
          'input[name="cidade"]:checked'
        )?.value || "";


      /* =========================
         LOJA
      ========================= */

      const lojaSelecionada =
        document.querySelector(
          'input[name="loja"]:checked'
        )?.value || "";



      /* =========================
        FILTROS ATUAIS
      ========================= */

      const portes = Array.from(
      document.querySelectorAll('input[name="porte"]:checked')
      ).map(input => input.value);
  
      const sexos = Array.from(
      document.querySelectorAll('input[name="sexo"]:checked')
      ).map(input => input.value);

      const idades = Array.from(
      document.querySelectorAll('input[name="idade"]:checked')
      ).map(input => input.value);

      const especies = Array.from(
      document.querySelectorAll('input[name="especie"]:checked')
      ).map(input => input.value);


      /* =========================
         VERIFICAR CADA ANIMAL
      ========================= */

      let petsVisiveis = 0; 

     cards.forEach(function(card) {


        const estado =
          card.dataset.estado;


        const cidade =
          card.dataset.cidade;


        const loja =
          card.dataset.loja;


        const porte =
          card.dataset.porte;


        const sexo =
          card.dataset.sexo;


        const dataNascimento =
        card.dataset.nascimento;


        const especie =
          card.dataset.especie;


        /* =========================
           COMPARAÇÕES
        ========================= */

        const correspondeEstado =
          !estadoSelecionado ||
          estado === estadoSelecionado;


        const correspondeCidade =
          !cidadeSelecionada ||
          cidade === cidadeSelecionada;


        const correspondeLoja =
          !lojaSelecionada ||
          loja === lojaSelecionada;


        const correspondePorte =
          portes.length === 0 ||
          portes.includes(porte);


        const correspondeSexo =
          sexos.length === 0 ||
          sexos.includes(sexo);


       const correspondeIdade =
        idades.length === 0 ||
     (
         dataNascimento &&
       idades.includes(obterFaixaIdade(dataNascimento ))
     );


        const correspondeEspecie =
          especies.length === 0 ||
          especies.includes(especie);


        /* =========================
           RESULTADO
        ========================= */

        const correspondeTudo =

          correspondeEstado &&
          correspondeCidade &&
          correspondeLoja &&
          correspondePorte &&
          correspondeSexo &&
          correspondeIdade &&
          correspondeEspecie;


        if (correspondeTudo) {
    card.style.display = "";
    petsVisiveis++; // Incrementa cada pet que passa no filtro
  } else {
    card.style.display = "none";
  }
});

// Exibe ou esconde a animação baseando-se no contador
const emptyState = document.getElementById("emptyState");
const petGrid = document.querySelector(".pet-grid");

if (petsVisiveis === 0) {
  emptyState.style.display = "flex";
  petGrid.style.display = "none";
} else {
  emptyState.style.display = "none";
  petGrid.style.display = "grid";
}
     
    
    }
    
    /*=================
    calcual idade
    =================*/
    function calcularIdade(dataNascimento) {
    const nascimento = new Date(dataNascimento + "T00:00:00");
    const hoje = new Date();

    let anos = hoje.getFullYear() - nascimento.getFullYear();
    let meses = hoje.getMonth() - nascimento.getMonth();

    if (hoje.getDate() < nascimento.getDate()) {
        meses--;
    }

    if (meses < 0) {
        anos--;
        meses += 12;
    }

    if (anos === 0) {

        if (meses === 0) {
            return "menos de 1 mês";
        }

        return `${meses} ${meses === 1 ? "mês" : "meses"}`;
    }

    if (meses === 0) {
        return `${anos} ${anos === 1 ? "ano" : "anos"}`;
    }

    return `${anos} ${anos === 1 ? "ano" : "anos"} e ${meses} ${meses === 1 ? "mês" : "meses"}`;
}


function atualizarIdadesCards() {

    const cards = document.querySelectorAll(".card");

    cards.forEach(function(card) {

        const dataNascimento = card.dataset.nascimento;
        const elementoIdade = card.querySelector(".idade-animal");

        if (elementoIdade && dataNascimento) {

            elementoIdade.textContent = calcularIdade(dataNascimento);

        }

    });
}
   
    function obterFaixaIdade(dataNascimento) {

    const nascimento =
        new Date(dataNascimento + "T00:00:00");

    const hoje = new Date();

    let anos =
        hoje.getFullYear() -
        nascimento.getFullYear();

    let meses =
        hoje.getMonth() -
        nascimento.getMonth();

    if (hoje.getDate() < nascimento.getDate()) {
        meses--;
    }

    if (meses < 0) {
        anos--;
        meses += 12;
    }

    const totalMeses =
        (anos * 12) + meses;


    /* 0 a 6 meses */
    if (totalMeses <= 6) {
        return "0-6m";
    }


    /* 7 meses a 5 anos */
    if (totalMeses <= 71) {
        return "7m-5a";
    }


    /* 6 a 9 anos */
    if (totalMeses <= 119) {
        return "6-9";
    }


    /* 10 anos ou mais */
    return "10+";
} 
