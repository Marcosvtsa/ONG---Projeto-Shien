    function aplicarFiltros() {

      const cards =
        document.querySelectorAll(".card");
        
    


      /* =========================
         ESTADO
      ========================= */

      const estadoSelecionado =
        document.querySelector(
          'input[name="uf"]:checked'
        )?.value || "";


      /* =========================
         CIDADE
      ========================= */

      const cidadeSelecionada =
        document.querySelector(
          'input[name="cidade"]:checked'
        )?.value || "";


      /* =========================
         LOJA
      ========================= */

      const lojaSelecionada =
        document.querySelector(
          'input[name="loja"]:checked'
        )?.value || "";



      /* =========================
        FILTROS ATUAIS
      ========================= */

      const portes = Array.from(
      document.querySelectorAll('input[name="porte"]:checked')
      ).map(input => input.value);
  
      const sexos = Array.from(
      document.querySelectorAll('input[name="sexo"]:checked')
      ).map(input => input.value);

      const idades = Array.from(
      document.querySelectorAll('input[name="idade"]:checked')
      ).map(input => input.value);

      const especies = Array.from(
      document.querySelectorAll('input[name="especie"]:checked')
      ).map(input => input.value);


      /* =========================
         VERIFICAR CADA ANIMAL
      ========================= */

      let petsVisiveis = 0; 

     cards.forEach(function(card) {


        const estado =
          card.dataset.estado;


        const cidade =
          card.dataset.cidade;


        const loja =
          card.dataset.loja;


        const porte =
          card.dataset.porte;


        const sexo =
          card.dataset.sexo;


        const dataNascimento =
        card.dataset.nascimento;


        const especie =
          card.dataset.especie;


        /* =========================
           COMPARAÇÕES
        ========================= */

        const correspondeEstado =
          !estadoSelecionado ||
          estado === estadoSelecionado;


        const correspondeCidade =
          !cidadeSelecionada ||
          cidade === cidadeSelecionada;


        const correspondeLoja =
          !lojaSelecionada ||
          loja === lojaSelecionada;


        const correspondePorte =
          portes.length === 0 ||
          portes.includes(porte);


        const correspondeSexo =
          sexos.length === 0 ||
          sexos.includes(sexo);


       const correspondeIdade =
        idades.length === 0 ||
     (
         dataNascimento &&
       idades.includes(obterFaixaIdade(dataNascimento ))
     );


        const correspondeEspecie =
          especies.length === 0 ||
          especies.includes(especie);


        /* =========================
           RESULTADO
        ========================= */

        const correspondeTudo =

          correspondeEstado &&
          correspondeCidade &&
          correspondeLoja &&
          correspondePorte &&
          correspondeSexo &&
          correspondeIdade &&
          correspondeEspecie;


        if (correspondeTudo) {
    card.style.display = "";
    petsVisiveis++; // Incrementa cada pet que passa no filtro
  } else {
    card.style.display = "none";
  }
});

// Exibe ou esconde a animação baseando-se no contador
const emptyState = document.getElementById("emptyState");
const petGrid = document.querySelector(".pet-grid");

if (emptyState) {
    if (petsVisiveis === 0) {
      emptyState.style.display = "block"; // Mostra o bloco fixo de texto do HTML
      if (petGrid) petGrid.style.display = "none"; // Esconde a grade de pets se estiver vazia
    } else {
      emptyState.style.display = "none"; // Oculta o aviso de nenhum pet encontrado
      if (petGrid) petGrid.style.display = "grid"; // Mostra a grade com os pets de volta
    }
  }
}
