    function carregarCidades(estado) {

      const listaCidades =
        document.getElementById("container-cidades");

      const listaLojas =
        document.getElementById("container-lojas");

        

        if (!listaCidades || !listaLojas) {
        console.error("Containers de cidades ou lojas não encontrados.");
        return; }


      // Limpa cidades antigas

      listaCidades.innerHTML = "";

      // Limpa lojas antigas

      listaLojas.innerHTML = `
        <p class="lojas-placeholder">

          Selecione uma cidade primeiro
          para visualizar as Lojas.

        </p>
      `;


      // Procura as cidades

      const cidades =
        cidadesPorEstado[estado] || [];


      // Caso não existam cidades

      if (cidades.length === 0) {

        listaCidades.innerHTML = `
          <p class="cidade-placeholder">

            Nenhuma cidade cadastrada
            para este estado.

          </p>
        `;

        aplicarFiltros();

        return;
      }


      // Cria as cidades (com a tag fechada corretamente)

      cidades.forEach(function(cidade) {

        const item =
          document.createElement("h5");


        item.innerHTML = `
          <input
            type="radio"
            name="cidade"
            value="${cidade}"
            onclick="selecionarCidade(this, '${cidade}')">

          ${cidade}
        `;


        listaCidades.appendChild(item);

      });


      aplicarFiltros();

    }


    /* =========================================
       MOSTRAR LOJAS DA CIDADE
    ========================================= */

    function carregarLojas(cidade) {

      const listaLojas =
        document.getElementById("container-lojas");


      listaLojas.innerHTML = "";


      const lojas =
        lojasPorCidades[cidade] || [];


      if (lojas.length === 0) {

        listaLojas.innerHTML = `
          <p class="lojas-placeholder">

            Nenhuma loja cadastrada
            para esta cidade.

          </p>
        `;

        return;
      }


      lojas.forEach(function(loja) {

        const item =
          document.createElement("h5");


        // Verifica se a loja está INATIVA

        const inativa =
          loja.toUpperCase().includes("INATIVO");


        if (inativa) {

          item.innerHTML = `
            <span
              style="
                color: gray;
                font-size: 0.85rem;
              ">

              ${loja}

            </span>
          `;

        } else {

          item.innerHTML = `
            <input
              type="radio"
              name="loja"
              value="${loja}"
              onclick="selecionarLoja(this, '${loja}')">

            ${loja}
          `;

        }


        listaLojas.appendChild(item);

      });

    }


    /* =========================================
       SELECIONAR CIDADE (MARCAR / DESMARCAR)
    ========================================= */

    function selecionarCidade(input, cidade) {

      // Se já estava selecionada, desmarca
      if (input.dataset.selecionada === "true") {

        input.checked = false;
        input.dataset.selecionada = "false";

        // Esconde as lojas
        document.getElementById("listaLojas").innerHTML = `
          <p class="lojas-placeholder">
            Selecione uma cidade primeiro
            para visualizar as Lojas.
          </p>
        `;

        aplicarFiltros();
        return;
      }

      // Remove o estado de seleção das outras cidades
      document
        .querySelectorAll('input[name="cidade"]')
        .forEach(function(cidadeInput) {
          cidadeInput.dataset.selecionada = "false";
        });

      // Marca a cidade atual
      input.dataset.selecionada = "true";

      // Carrega as lojas da cidade
      carregarLojas(cidade);
      aplicarFiltros();

    }


